export const CONTENT_API_CONTRACTS: readonly ContentApiContract[] = Object.freeze(contracts);
export type ContentApiContractKey = (typeof contracts)[number]['key'];
export const CONTENT_OPENAPI_DOCUMENT = buildContentOpenApiDocument(CONTENT_API_CONTRACTS);

export function findContentApiContract(key: ContentApiContractKey): ContentApiContract {
  const found = contracts.find((candidate) => candidate.key === key);
  if (!found) throw new Error(`Unknown Content API contract: ${key}`);
  return found;
}

function contract(
  key: string,
  method: ContentApiMethod,
  path: string,
  policy: ContentApiContract['policy'],
  permission: ContentApiContract['permission'],
  idempotency: ContentIdempotency,
  bodySchema: z.ZodType | null,
  paramsSchema: z.ZodType | null,
  querySchema: z.ZodType | null,
  requestName: string,
  responseName: string,
  responseSchema: z.ZodType,
  successStatus: ContentApiContract['successStatus'],
): ContentApiContract {
  return {
    bodySchema,
    idempotency,
    key,
    method,
    paramsSchema,
    path,
    permission,
    policy,
    querySchema,
    requestName,
    responseName,
    responseSchema,
    successStatus,
  };
}

