export type ContentApiMethod = 'DELETE' | 'GET' | 'PATCH' | 'POST';
export type ContentIdempotency =
  '-' | 'key+body_hash' | 'key+content_hash' | 'key+version' | 'resource+version';

export interface ContentApiContract {
  readonly bodySchema: z.ZodType | null;
  readonly idempotency: ContentIdempotency;
  readonly key: string;
  readonly method: ContentApiMethod;
  readonly paramsSchema: z.ZodType | null;
  readonly path: string;
  readonly permission: Extract<
    PermissionCode,
    | 'content.briefs.manage'
    | 'content.production.manage'
    | 'content.read'
    | 'review.decide'
    | 'tenant.workspaces.manage'
  >;
  readonly policy: Extract<
    PolicyCode,
    | 'content_editor_or_admin'
    | 'reviewer_or_admin'
    | 'strategy_or_content_editor_or_admin'
    | 'tenant_admin_or_owner'
    | 'tenant_member'
  >;
  readonly querySchema: z.ZodType | null;
  readonly requestName: string;
  readonly responseName: string;
  readonly responseSchema: z.ZodType;
  readonly successStatus: 200 | 201 | 202 | 204;
}

