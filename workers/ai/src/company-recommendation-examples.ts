export function recommendationWritingExampleForTopic(topic: string): string {
  const divider = RECOMMENDATION_WRITING_EXAMPLES.indexOf('网页示例输入');
  if (/办公室|仓库|企业搬迁|设备/u.test(topic))
    return `以下是匿名句法示例，名称与事实不可移入当前企业：\n${RECOMMENDATION_WRITING_EXAMPLES.slice(divider)}`;
  if (/日式|家庭|衣物|厨房|收纳/u.test(topic))
    return RECOMMENDATION_WRITING_EXAMPLES.slice(0, divider);
  return '';
}

